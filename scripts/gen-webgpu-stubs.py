#!/usr/bin/env python3
# Writes app/src/child/webgpu_stubs.c: a do-nothing definition of every function Dawn's webgpu.h declares, for the
# CPU web process (wisp-web.bin). The web process's WebKit build is one for both web processes and has WebCore's
# WebGPU on Dawn (WebKit patch 0039); the CPU web process has no GPU and no Dawn, and its WebGPU never starts
# (wisp_webgpu_usable is false there), but the link still needs what WebKit's code refers to.
#
#   python3 scripts/gen-webgpu-stubs.py [webgpu.h] [out.c]
#
# (defaults: ~/wisp-build/build/dawn/gen/include/dawn/webgpu.h, app/src/child/webgpu_stubs.c). Run it again when
# Dawn changes: the stubs include the header, so a changed signature fails to compile, and a new function WebKit
# calls fails wisp-web's link.
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
header = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/wisp-build/build/dawn/gen/include/dawn/webgpu.h")
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "app", "src", "child", "webgpu_stubs.c")

DECL = re.compile(r"^WGPU_EXPORT\s+(?P<ret>.+?)\s*\b(?P<name>wgpu\w+)\((?P<params>.*)\)\s*WGPU_FUNCTION_ATTRIBUTE;\s*$")

functions = []
with open(header, encoding="utf-8") as f:
    for line in f:
        m = DECL.match(line)
        if m:
            functions.append((m["ret"].strip(), m["name"], m["params"].strip()))
if len(functions) < 100:
    sys.exit(f"{header}: only {len(functions)} declarations found: not Dawn's webgpu.h?")
names = [name for _, name, _ in functions]
if len(set(names)) != len(names):
    sys.exit(f"{header}: a function declared twice")

lines = [
    "// Generated by scripts/gen-webgpu-stubs.py from Dawn's webgpu.h: do not edit; run the script again when Dawn",
    "// changes.",
    "//",
    "// The CPU web process (wisp-web.bin) has WebKit's WebGPU code (one WebKit build serves both web processes: WebKit",
    "// patch 0039) but no Dawn, as it has no GPU. WebGPU::create asks wisp_webgpu_usable, which only the GPU web",
    "// process defines (child/child_main.cpp; WebKit's weak definition answers false here), so none of these ever",
    "// runs: they let the link resolve what WebKit refers to. Each does nothing and returns zero.",
    "#include <dawn/webgpu.h>",
    "#include <string.h>",
    "",
    "#pragma clang diagnostic ignored \"-Wunused-parameter\"",
    "",
]
for ret, name, params in functions:
    if params in ("", "void"):
        params = "void"
    if ret == "void":
        lines.append(f"{ret} {name}({params}) {{ }}")
    else:
        lines.append(f"{ret} {name}({params}) {{ {ret} r; memset(&r, 0, sizeof r); return r; }}")
lines.append("")

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print(f"{os.path.normpath(out)}: {len(functions)} functions from {header}")
